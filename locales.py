def get_text(lang: str, key: str, fallback: str = "") -> str:
    # 1. تحديد اللغة المطلوبة أو الاعتماد على الإنجليزية كافتراضي
    target_lang = lang if lang in TRANSLATIONS else "en"
    
    # 2. جلب النص من اللغة المطلوبة
    text = TRANSLATIONS.get(target_lang, {}).get(key)
    
    # 3. إذا لم يوجد المفتاح في تلك اللغة، يتم الجلب من الإنجليزية
    if text is None:
        text = TRANSLATIONS.get("en", {}).get(key)
        
    # 4. إذا لم يوجد حتى في الإنجليزية، يتم استخدام الـ fallback أو اسم المفتاح نفسه
    if text is None:
        return fallback if fallback else key

    return text